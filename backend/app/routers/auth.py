# FastAPI utilities 
from fastapi import APIRouter, Depends, HTTPException, status, Response, Cookie

# SQLAlchemy database session
from sqlalchemy.orm import Session

from app.models.refresh_token import RefreshToken

from datetime import datetime, timezone

from fastapi import Cookie, Response

# Database dependency
from app.database import get_db

# SQLAlchemy User database model
from app.models.user import User

# Pydantic request/response schemas
from app.schemas.auth import (
    UserCreate,
    UserResponse,
    UserLogin,
)

# Authentication/security utilities
from app.core.security import (
    hash_password,
    verify_password,
    create_access_token,
    get_current_user,
    get_refresh_token_expiry,
    create_refresh_token,
    hash_refresh_token,
    is_access_token_valid,
    get_valid_refresh_token
)



"""
    Create a router for authentication-related endpoints.

    prefix="/auth" means every endpoint in this router
    will start with /auth.

    For example:
      @router.post("/login")
    becomes:
      POST /auth/login

    tags are used to group these endpoints in the
    automatically generated Swagger documentation.
"""
router = APIRouter(
    prefix="/auth",
    tags=["Authentication"],
)


# ---------------------------------------------------------
# SIGNUP
# ---------------------------------------------------------

@router.post(
    "/signup",
    response_model=UserResponse,
    status_code=status.HTTP_201_CREATED,
)
def signup(
    # FastAPI reads the request body and validates it
    # using the UserCreate Pydantic schema.
    user_data: UserCreate,

    # FastAPI automatically provides a database session
    # using our get_db dependency.
    db: Session = Depends(get_db),
):
    # Check whether a user with this email already exists.
    existing_user = (
        db.query(User)
        .filter(User.email == user_data.email)
        .first()
    )

    # If the email is already registered, stop the request
    # and return HTTP 400 Bad Request.
    if existing_user:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Email already registered",
        )

    # NEVER store the user's plain-text password.
    #
    # Convert the password into a secure password hash
    # before storing it in the database.
    hashed_password = hash_password(user_data.password)

    # Create a new SQLAlchemy User object.
    user = User(
        email=user_data.email,
        name=user_data.name,
        password_hash=hashed_password,
    )

    # Add the new user to the current database session.
    db.add(user)

    # Commit the transaction so the user is actually
    # written to the database.
    db.commit()

    # Refresh the object so SQLAlchemy loads values
    # generated by the database, such as the user ID.
    db.refresh(user)

    # Return the newly created user.
    #
    # FastAPI will format the response according to
    # the UserResponse schema.
    return user


